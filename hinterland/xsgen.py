"""Write src/xs/Hinterland/generated_ids.xs from IDs assigned by the data-mod build."""
from pathlib import Path

from hinterland import SRC_XS

GENERATED_IDS = SRC_XS / "Hinterland" / "generated_ids.xs"

# Every constant the XS expects, with the placeholder used before the dat is built.
DEFAULTS = {
    "cSupplyCartId": -1,
    "cLoadedSupplyCartId": -1,
    "cPalaceId": -1,
    "cDarkWatchTowerId": -1,
    "cDarkGuardTowerId": -1,
    "cDarkKeepId": -1,
    "cDarkBombardTowerId": -1,
    "cDarkDonjonId": -1,
    "cDarkTownCenterCastleId": -1,
    "cDarkTownCenterImperialId": -1,
    "cDarkEconomicTownCenterId": -1,
    "cDarkDefensiveTownCenterId": -1,
    "cDarkMilitaryTownCenterId": -1,
    "cDarkKrepostId": -1,
    "cDarkHarborId": -1,
    "cDarkFortifiedChurchId": -1,
    "cDarkFortifiedOutpostId": -1,
    "cDarkFortifiedOutpost2Id": -1,
    "cDarkDockCastleId": -1,
    "cDarkDockImperialId": -1,
    "cDarkMillCastleId": -1,
    "cDarkMillImperialId": -1,
    "cDarkLumberCampCastleId": -1,
    "cDarkLumberCampImperialId": -1,
    "cDarkMiningCampCastleId": -1,
    "cDarkMiningCampImperialId": -1,
    "cDarkShipyardCastleId": -1,
    "cDarkShipyardImperialId": -1,
    "cDarkPortCastleId": -1,
    "cDarkPortImperialId": -1,
    "cDarkFolwarkId": -1,
    "cDarkSettlementId": -1,
    "cDarkMuleCartId": -1,
}

HEADER = """\
// GENERATED by `python -m hinterland build` from the data mod. Do not edit by hand.
// Placeholder values (-1) mean the data mod has not been built yet; the XS
// skips cart logic while cSupplyCartId < 0.
"""


def render(new_ids: dict[str, int]) -> str:
    unknown = set(new_ids) - set(DEFAULTS)
    if unknown:
        raise ValueError(f"Add these to xsgen.DEFAULTS: {sorted(unknown)}")
    lines = [HEADER]
    for name, default in DEFAULTS.items():
        lines.append(f"extern const int {name} = {new_ids.get(name, default)};")
    return "\n".join(lines) + "\n"


def write(new_ids: dict[str, int], path: Path = GENERATED_IDS) -> None:
    path.write_text(render(new_ids), encoding="utf-8", newline="\n")
